package com.nutomic.syncthingandroid.model

import com.nutomic.syncthingandroid.util.splitLikeJava

/**
 * Sources:
 * - https://github.com/syncthing/syncthing/tree/master/lib/config
 * - https://github.com/syncthing/syncthing/blob/master/lib/config/guiconfiguration.go
 */
class Gui {
    @JvmField var enabled: Boolean = true

    /** REST: useTLS, XML: tls */
    @JvmField var useTLS: Boolean = false
    @JvmField var address: String? = "127.0.0.1:8384"
    @JvmField var user: String? = null
    @JvmField var password: String? = null
    @JvmField var apiKey: String? = null // Automatically generated by SyncthingNative

    /** Available: default, dark, black */
    @JvmField var theme: String = "default"

    // omitEmpty
    @JvmField var insecureAdminAccess: Boolean = false
    @JvmField var insecureAllowFrameLoading: Boolean = false
    @JvmField var insecureSkipHostCheck: Boolean = false

    val bindAddress: String
        get() = addressPart(0)

    val bindPort: String
        get() = addressPart(1)

    private fun addressPart(index: Int): String {
        val split = (address ?: return "").splitLikeJava(":")
        return if (split.size <= index) "" else split[index]
    }
}
